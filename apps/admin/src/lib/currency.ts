export function formatCurrency(amount: number, currencyCode: string, locale = 'en-US'): string {
  return new Intl.NumberFormat(locale, {
    style: 'currency',
    currency: currencyCode,
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(amount);
}

export function formatCurrencyCompact(amount: number, currencyCode: string): string {
  if (amount >= 1_000_000) return `${formatCurrency(amount / 1_000_000, currencyCode)}M`;
  if (amount >= 1_000) return `${formatCurrency(amount / 1_000, currencyCode)}K`;
  return formatCurrency(amount, currencyCode);
}

