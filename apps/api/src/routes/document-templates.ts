function escapeHtml(str: string): string {
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

/** Substitute all {{variableName}} occurrences with provided values */
function substituteVariables(htmlBody: string, values: Record<string, string>): string {
  return htmlBody.replace(/\{\{(\w+)\}\}/g, (_, name: string) => values[name] ?? '');
}

