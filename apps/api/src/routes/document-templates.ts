/** Extract unique {{variableName}} tokens from HTML body */
function extractVariables(htmlBody: string): string[] {
  const regex = /\{\{(\w+)\}\}/g;
  const names = new Set<string>();
  let match: RegExpExecArray | null;
  while ((match = regex.exec(htmlBody)) !== null) {
    names.add(match[1]!);
  }
  return Array.from(names);
}

/** Merge auto-extracted variable names with any explicitly provided definitions */
function mergeVariables(
  htmlBody: string,
  explicit: Array<{ name: string; label?: string; defaultValue?: string; required?: boolean }>,
): Array<{ name: string; label: string; defaultValue?: string; required?: boolean }> {
  const extracted = extractVariables(htmlBody);
  const explicitMap = new Map(explicit.map((v) => [v.name, v]));

  return extracted.map((name) => {
    const def = explicitMap.get(name);
    return {
      name,
      label: def?.label ?? name,
      ...(def?.defaultValue !== undefined ? { defaultValue: def.defaultValue } : {}),
      ...(def?.required !== undefined ? { required: def.required } : {}),
    };
  });
}

